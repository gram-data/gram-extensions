#!/usr/bin/env python3
"""Refresh versions.toml with the latest GitHub release of each registry entry.

Writes the file only when a version changed, so `updated_at` records the last
time a release changed rather than the last time the check ran. An entry whose
release cannot be read (a private repository, a network error) keeps its
previous version and logs a warning.
"""
import json
import subprocess
import sys
import tomllib
from datetime import datetime, timezone

REGISTRY = "registry.toml"
VERSIONS = "versions.toml"


def load(path):
    try:
        with open(path, "rb") as f:
            return tomllib.load(f)
    except FileNotFoundError:
        return {}


def latest(github):
    out = subprocess.run(
        ["gh", "api", f"repos/{github}/releases/latest"],
        capture_output=True,
        text=True,
    )
    if out.returncode != 0:
        raise RuntimeError(out.stderr.strip() or "gh api failed")
    return json.loads(out.stdout)["tag_name"].lstrip("v")


def main():
    registry = load(REGISTRY)
    old = load(VERSIONS).get("versions", {})
    new = {}
    for ext in registry.get("extension", []):
        name = ext["name"]
        try:
            new[name] = latest(ext["github"])
        except Exception as e:
            print(f"warning: {name}: {e}", file=sys.stderr)
            if name in old:
                new[name] = old[name]
    if new == old:
        print("versions unchanged")
        return
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Generated by scripts/update-versions.py. Do not edit.",
        f'updated_at = "{stamp}"',
        "",
        "[versions]",
    ]
    lines += [f'{name} = "{version}"' for name, version in sorted(new.items())]
    with open(VERSIONS, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"updated: {new}")


main()
